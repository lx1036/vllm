from fastsafetensors import fastsafe_open, cpp
import torch

def main():
    filenames = ["a.safetensors", "b.safetensors"]
    device = "cuda:0" if torch.cuda.is_available() else "cpu"
    framework = "torch"

    with fastsafe_open(
            filenames,
            device=device,
            nogds=not cpp.is_cufile_found(),
            framework=framework,
    ) as f:
        print(f"a0: {f.get_tensor(name='a0')}")
        print(f"b0: {f.get_tensor(name='b0')}")

